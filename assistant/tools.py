"""Vault tools the bot can call. The model decides WHAT to do; this file decides
what's ALLOWED, so the vault rules hold even if the model misunderstands them.

- search_vault: finds notes by name and by lines containing all the given words
- read_note:    reads a note by path or [[name]]
- list_tags:    tags already in use, so new entries reuse them
- list_tasks:   open '- [ ]' tasks across the vault, optionally by tag
- capture:      appends one entry or #todo task to today's daily note
- remember:     appends one fact to Agent/MEMORY.md
- propose_edit: validates a change to an existing note but does NOT write it.
                main.py shows it to the user with Approve/Reject buttons, and only
                apply_edit() (called on Approve) touches the file.
- escalate:     hands the message to a stronger model

Never readable: Private/, dot-folders, .sync-conflict- files, anything outside the vault.
Writes are append-only, except edits the user approved.
"""

import difflib
import os
import re
from collections import Counter
from datetime import date, datetime
from pathlib import Path

from claude_agent_sdk import create_sdk_mcp_server, tool

MEMORY_FILE = "Agent/MEMORY.md"
MEMORY_HEADER = "# Memory\n\nThings the user has told the Discord assistant. See also [[about-me]].\n\n"
DAILY_DIR = os.environ.get("DAILY_DIR", "Agent/daily").strip("/")

# Folders never scanned or readable
SKIP_DIRS = {"Private", ".obsidian", ".stversions", ".stfolder", ".trash", ".git"}

MAX_READ_CHARS = 20_000
MAX_PROPOSALS_PER_MESSAGE = 3
MAX_HITS = 40
MAX_TASKS = 60

# '#tag' but not inside a word, URL or heading ('# Heading' has a space after #)
TAG_RE = re.compile(r"(?<![\w/&#])#([A-Za-z][\w/-]*)")
FRONTMATTER_TAGS_RE = re.compile(r"^tags:\s*\[([^\]]*)\]\s*$", re.M)
OPEN_TASK_RE = re.compile(r"^\s*[-*] \[ \] (.+)$")
LIST_MARKER_RE = re.compile(r"^(?:[-*]\s+)?(?:\[[ xX]\]\s+)?(?:[-*]\s+)?(?:\[[ xX]\]\s+)?")
DUE_RE = re.compile(r"📅\s*(\d{4}-\d{2}-\d{2})")
TASKS_FILE = "Tasks.md"  # generated by write_tasks_index(); never edited by hand
INDEX_FILE = "Vault index.md"  # generated by write_vault_index(); never edited by hand

# One line per top-level folder in the index. Edit these to match your vault:
# folders that aren't listed still appear in the index, just without a description.
FOLDER_INFO = {
    "Me": "Facts about you: [[about-me]], [[Devices]].",
    "Projects": "One note per project.",
    "Ideas": "Ideas to come back to.",
    "Home": "Everyday life: meals, shopping, the house.",
    "Misc": "Anything that doesn't fit elsewhere.",
    "Inbox": "New notes waiting to be sorted.",
    "Agent": "The assistant's own files.",
}
FOLDER_ORDER = ["Me", "Projects", "Ideas", "Home", "Misc", "Inbox", "Agent"]

TOOL_NAMES = [f"mcp__vault__{n}" for n in (
    "search_vault", "read_note", "list_tags", "list_tasks", "capture", "remember", "propose_edit")]


class VaultError(Exception):
    """A rule was broken or the request can't be done. The message goes back to the model."""


# ---------- file helpers ----------

def safe_path(vault: Path, rel: str) -> tuple[Path, str]:
    """Resolve a vault-relative note path, refusing anything off-limits.
    Returns (absolute path, normalised vault-relative path)."""
    rel = rel.strip().strip("/")
    if not rel:
        raise VaultError("No path given.")
    if not rel.endswith(".md"):
        rel += ".md"
    root = vault.resolve()
    path = (root / rel).resolve()
    try:
        parts = path.relative_to(root).parts
    except ValueError:
        raise VaultError("That path is outside the vault.") from None
    if any(p in SKIP_DIRS or p.startswith(".") for p in parts):
        raise VaultError("That folder is off-limits.")
    if ".sync-conflict-" in path.name:
        raise VaultError("Sync-conflict files must not be touched. Tell the user it exists instead.")
    return path, "/".join(parts)


def iter_notes(vault: Path):
    """Every readable .md note in the vault."""
    for dirpath, dirs, files in os.walk(vault):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS and not d.startswith(".")]
        for name in files:
            if name.endswith(".md") and ".sync-conflict-" not in name:
                yield Path(dirpath, name)


def note_names(vault: Path) -> dict[str, Path]:
    """Lowercase note name -> path, which is how [[wikilinks]] resolve."""
    return {p.stem.lower(): p for p in iter_notes(vault)}


def find_note(vault: Path, ref: str) -> tuple[Path, str]:
    """A note by vault-relative path ('Me/Devices.md') or by name ('Devices', '[[Devices]]').
    Returns (absolute path, vault-relative path); raises VaultError if it's missing or off-limits."""
    ref = ref.strip().strip("[]").split("|")[0]
    path, rel = safe_path(vault, ref)
    if path.is_file():
        return path, rel
    match = note_names(vault).get(Path(ref).stem.lower())
    if match is None:
        raise VaultError(f"No readable note called '{ref}'. Use search_vault to find it.")
    return safe_path(vault, match.relative_to(vault).as_posix())


def read_raw(path: Path) -> str:
    # newline="" keeps Windows line endings intact, so edits don't rewrite the whole file
    with path.open(encoding="utf-8", newline="") as f:
        return f.read()


def write_raw(path: Path, text: str) -> None:
    with path.open("w", encoding="utf-8", newline="") as f:
        f.write(text)


# ---------- the operations ----------

def append_memory(vault: Path, fact: str) -> str | None:
    """Append '- fact' to MEMORY.md. Returns the line, or None if it was already there."""
    fact = " ".join(fact.split())  # always a single line
    if not fact:
        raise VaultError("The fact is empty.")
    path, _ = safe_path(vault, MEMORY_FILE)
    existing = read_raw(path) if path.exists() else ""
    line = f"- {fact}"
    if line in existing.splitlines():
        return None
    nl = "\r\n" if "\r\n" in existing else "\n"
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8", newline="") as f:
        if not existing.strip():
            f.write(MEMORY_HEADER)
        elif not existing.endswith("\n"):
            f.write(nl)
        f.write(line + nl)
    return line


def read_note(vault: Path, ref: str) -> str:
    path, rel = find_note(vault, ref)
    text = read_raw(path).replace("\r\n", "\n")
    if len(text) > MAX_READ_CHARS:
        text = text[:MAX_READ_CHARS] + f"\n\n[Cut at {MAX_READ_CHARS} characters.]"
    return f"# {rel}\n\n{text}"


def check_edit(vault: Path, ref: str, old: str, new: str) -> str:
    """Validate a proposed edit without writing anything. Returns the vault-relative path."""
    path, rel = find_note(vault, ref)
    if not old:
        raise VaultError("old_text is empty. Copy the exact text you want to replace.")
    if old == new:
        raise VaultError("old_text and new_text are the same.")
    count = read_raw(path).replace("\r\n", "\n").count(old)
    if count == 0:
        raise VaultError("old_text was not found. Read the note and copy the text exactly.")
    if count > 1:
        raise VaultError(f"old_text appears {count} times. Include more surrounding text.")
    return rel


def apply_edit(vault: Path, rel: str, old: str, new: str) -> None:
    """Called only after the user clicks Approve. Re-checks, since the note may have changed since."""
    check_edit(vault, rel, old, new)
    path, _ = safe_path(vault, rel)
    raw = read_raw(path)
    crlf = "\r\n" in raw
    text = raw.replace("\r\n", "\n").replace(old, new, 1)
    write_raw(path, text.replace("\n", "\r\n") if crlf else text)


def render_diff(old: str, new: str, limit: int = 1500) -> str:
    lines = difflib.unified_diff(old.splitlines(), new.splitlines(), lineterm="", n=1)
    body = "\n".join(l for l in lines if not l.startswith(("---", "+++", "@@")))
    body = body.replace("```", "'''")
    if len(body) > limit:
        body = body[:limit] + "\n... (truncated)"
    return body


# Near-duplicates of the core tags, merged so the vault has one tag per meaning
TAG_ALIASES = {"ideas": "idea", "todos": "todo", "task": "todo", "tasks": "todo",
               "questions": "question"}


def normalise_tags(raw: str) -> list[str]:
    """'Todo, #praktik  side-project' -> ['todo', 'praktik', 'side-project']"""
    tags = []
    for part in re.split(r"[,\s]+", raw):
        tag = re.sub(r"[^\w/-]", "", part.lstrip("#").lower())
        tag = TAG_ALIASES.get(tag, tag)
        if tag and tag not in tags:
            tags.append(tag)
    return tags


CODE_RE = re.compile(r"```.*?```|`[^`\n]*`", re.S)


def tags_in(text: str) -> list[str]:
    """Inline #tags plus frontmatter 'tags: [a, b]', lowercased. Tags inside `code`
    are examples (e.g. in CLAUDE.md), not tags, so they don't count."""
    tags = [t.lower() for t in TAG_RE.findall(CODE_RE.sub(" ", text))]
    if text.startswith("---"):
        end = text.find("\n---", 3)
        m = FRONTMATTER_TAGS_RE.search(text[:end] if end != -1 else "")
        if m:
            tags += normalise_tags(m.group(1))
    return tags


def _lines(path: Path) -> list[str]:
    try:
        return path.read_text(encoding="utf-8").splitlines()
    except (OSError, UnicodeDecodeError):
        return []


def search_notes(vault: Path, query: str) -> str:
    words = [w.lower() for w in query.split()]
    if not words:
        return "Empty query."
    hits, total = [], 0
    for path in iter_notes(vault):
        rel = path.relative_to(vault).as_posix()
        found = [f"{rel} (note name matches)"] if all(w in rel.lower() for w in words) else []
        found += [f"{rel}:{n}: {line.strip()[:200]}"
                  for n, line in enumerate(_lines(path), 1) if all(w in line.lower() for w in words)]
        total += len(found)
        hits += found[: max(0, MAX_HITS - len(hits))]
    if not hits:
        return f"No matches for '{query}'. Try other or fewer words."
    more = f"\n…and {total - len(hits)} more. Narrow the query." if total > len(hits) else ""
    return "\n".join(hits) + more


def list_tags_text(vault: Path) -> str:
    counts = Counter()
    for path in iter_notes(vault):
        if path.relative_to(vault).as_posix() == TASKS_FILE:
            continue
        counts.update(tags_in("\n".join(_lines(path))))
    if not counts:
        return "No tags used yet."
    return ", ".join(f"#{t} ({n})" for t, n in counts.most_common(60))


def all_open_tasks(vault: Path) -> list[tuple[str, int, str]]:
    """(note path, line number, task text) for every open '- [ ]' task."""
    found = []
    for path in iter_notes(vault):
        rel = path.relative_to(vault).as_posix()
        if rel == TASKS_FILE:
            continue
        for n, line in enumerate(_lines(path), 1):
            m = OPEN_TASK_RE.match(line)
            if m:
                found.append((rel, n, m.group(1).strip()))
    return found


def write_tasks_index(vault: Path) -> bool:
    """Rewrite Tasks.md as a plain list of every open task. Returns True if it changed."""
    tasks = all_open_tasks(vault)
    out = ["# Tasks", "",
           "Every open task in the vault, updated automatically by the assistant. Tick a task "
           "off in the note it lives in (click the note's name). All notes: [[Vault index]].", ""]
    dated = sorted((DUE_RE.search(t).group(1), rel, t) for rel, _, t in tasks if DUE_RE.search(t))
    if dated:
        out += ["## By date", ""]
        out += [f"- **{d}**: {' '.join(DUE_RE.sub('', t).split())} ([[{Path(rel).stem}]])" for d, rel, t in dated]
        out.append("")
    by_note: dict[str, list[str]] = {}
    for rel, _, t in tasks:
        by_note.setdefault(rel, []).append(t)
    out += ["## By note", ""] if by_note else ["No open tasks.", ""]
    for rel in sorted(by_note, key=lambda r: (not r.startswith(DAILY_DIR), r), reverse=False):
        out += [f"### [[{Path(rel).stem}]]", ""] + [f"- {t}" for t in by_note[rel]] + [""]
    text = "\n".join(out).rstrip() + "\n"
    # write without a single '#tag' parse problem: tags stay as they are in the source lines
    path = vault / TASKS_FILE
    if path.exists() and read_raw(path) == text:
        return False  # unchanged: don't touch the file, so Syncthing has nothing to sync
    write_raw(path, text)
    return True


def write_vault_index(vault: Path) -> bool:
    """Rewrite Vault index.md from the folders: every note, linked, grouped by folder.
    Returns True if it changed."""
    notes = [p.relative_to(vault) for p in iter_notes(vault)]
    stems = Counter(n.stem.lower() for n in notes)

    def link(rel: Path) -> str:
        name = rel.stem
        target = rel.with_suffix("").as_posix() if stems[name.lower()] > 1 else name  # unambiguous
        label = name if len(name) <= 45 else name[:42].rstrip() + "…"
        return f"[[{target}]]" if (target == name and label == name) else f"[[{target}|{label}]]"

    folders: dict[str, list[Path]] = {}
    for rel in notes:
        if len(rel.parts) == 1:
            continue  # root files (CLAUDE.md, Tasks.md, this index) are described in the intro
        folders.setdefault(rel.parts[0], []).append(rel)

    out = ["---", "tags: [index]", "---", "# Vault index", "",
           "Every note in the vault by folder, updated automatically by the assistant (don't edit "
           "by hand). Open tasks are in [[Tasks]]; the rules for AI assistants are in `CLAUDE.md`.", ""]
    order = [f for f in FOLDER_ORDER if f in folders or f in FOLDER_INFO] + sorted(set(folders) - set(FOLDER_ORDER))
    for folder in order:
        out += [f"## {folder}"]
        if FOLDER_INFO.get(folder):
            out.append(FOLDER_INFO[folder])
        items = sorted(folders.get(folder, []), key=lambda r: r.as_posix().lower())
        if folder == "Agent":  # daily notes pile up; show the folder, not every day
            daily = [r for r in items if r.as_posix().startswith(DAILY_DIR + "/")]
            items = [r for r in items if r not in daily]
            if daily:
                out.append(f"- Daily notes in `{DAILY_DIR}/` (latest: {link(max(daily, key=lambda r: r.stem))})")
        sub_seen = None
        for rel in items:
            sub = "/".join(rel.parts[1:-1])
            if sub and sub != sub_seen:
                out.append(f"- **{sub}/**")
                sub_seen = sub
            out.append(("  " if sub else "") + f"- {link(rel)}")
        if not items and folder not in ("Agent",):
            out.append("- (empty)")
        out.append("")
    out += ["## Private", "Not visible to the assistant. Not listed here.", ""]
    text = "\n".join(out).rstrip() + "\n"
    path = vault / INDEX_FILE
    if path.exists() and read_raw(path) == text:
        return False
    write_raw(path, text)
    return True


def open_tasks(vault: Path, tag: str) -> str:
    want = (normalise_tags(tag) or [None])[0]
    found = []
    for path in iter_notes(vault):
        rel = path.relative_to(vault).as_posix()
        if rel == TASKS_FILE:
            continue
        for n, line in enumerate(_lines(path), 1):
            m = OPEN_TASK_RE.match(line)
            if m and (want is None or want in tags_in(line)):  # exact tag: #praktik ≠ #praktikrapport
                found.append(f"{rel}:{n}: {m.group(1).strip()}")
    if not found:
        return "No open tasks" + (f" tagged #{want}." if want else ".")
    more = f"\n…and {len(found) - MAX_TASKS} more." if len(found) > MAX_TASKS else ""
    return "\n".join(found[:MAX_TASKS]) + more


def capture_entry(vault: Path, text: str, task: bool, tags: str, links: str,
                  due: str = "") -> tuple[str, str, list[str]]:
    """Append one line to today's daily note. Links are kept only if the note exists.
    Returns (line written, daily note path, links that were dropped)."""
    # Tags typed into the text itself are moved to the tag list, so none appears twice
    inline = TAG_RE.findall(text)
    text = " ".join(TAG_RE.sub(" ", text).split())
    text = LIST_MARKER_RE.sub("", text)  # the tool adds '- ' / '- [ ] ' itself
    typed_due = DUE_RE.search(text)  # a '📅 date' typed into the text becomes the due date
    if typed_due:
        due = due or typed_due.group(1)
        text = " ".join(DUE_RE.sub(" ", text).split())
    if not text:
        raise VaultError("Nothing saved: text was empty.")
    tag_list = normalise_tags(tags + " " + " ".join(inline))
    if task and "todo" not in tag_list:
        tag_list.insert(0, "todo")

    names = note_names(vault)
    kept, dropped = [], []
    for raw in links.split(","):
        name = raw.strip().strip("[]").split("|")[0].removesuffix(".md")
        if not name:
            continue
        match = names.get(Path(name).stem.lower())
        if match and match.stem not in kept:
            kept.append(match.stem)  # the note's real capitalisation
        elif not match:
            dropped.append(name)

    due = due.strip()
    if due:
        try:
            due = date.fromisoformat(due).isoformat()
        except ValueError:
            raise VaultError(f"due must be a date like 2026-11-30, not '{due}'.") from None
        if not task:
            raise VaultError("Only tasks can have a due date; set task: true.")

    line = f"- [ ] {text}" if task else f"- {datetime.now().strftime('%H:%M')} {text}"
    if due:
        line += f" 📅 {due}"  # Tasks plugin format; the heartbeat reminds on this date
    suffix = " ".join([f"#{t}" for t in tag_list] + [f"[[{l}]]" for l in kept])
    if suffix:
        line += " " + suffix

    path, rel = safe_path(vault, f"{DAILY_DIR}/{date.today().isoformat()}.md")
    path.parent.mkdir(parents=True, exist_ok=True)
    existing = read_raw(path) if path.exists() else ""
    with path.open("a", encoding="utf-8", newline="") as f:  # append only
        if not existing:
            f.write(f"# {date.today().isoformat()}\n\nIndex: [[Vault index]]\n\n")
        elif not existing.endswith("\n"):
            f.write("\n")
        f.write(line + "\n")
    return line, rel, dropped


# ---------- the MCP server the SDK talks to ----------

def _ok(text: str) -> dict:
    return {"content": [{"type": "text", "text": text}]}


def _err(text: str) -> dict:
    return {"content": [{"type": "text", "text": text}], "is_error": True}


def make_vault_server(vault: Path, actions: list[dict], escalate_to: list[str] | None = None):
    """Build the tool server for one request. Every write, proposal or escalation is
    recorded in `actions`, so main.py can show the user exactly what happened.
    `escalate_to` lists the models this request may hand over to (empty = no escalate tool)."""
    escalate_to = escalate_to or []

    @tool(
        "remember",
        "Save one durable fact about the user to Agent/MEMORY.md, which is loaded into every "
        "future conversation. One short, self-contained sentence per call. Only for facts "
        "with no home in an existing note. Never use this for something that belongs in a "
        "note (SOUL.md says which notes hold what, e.g. machines in Me/Devices.md, job and "
        "skills in Me/about-me.md); use propose_edit for those, even if the note "
        "doesn't mention it yet.",
        {"fact": str},
    )
    async def remember(args):
        try:
            line = append_memory(vault, args["fact"])
        except VaultError as e:
            return _err(str(e))
        if line is None:
            return _ok("That fact is already in memory; nothing was written.")
        actions.append({"type": "remembered", "line": line})
        return _ok(f"Saved to {MEMORY_FILE}: {line}")

    @tool(
        "search_vault",
        "Search the user's notes: matches note paths (folder names too, e.g. 'music') and lines "
        "containing ALL the given words, case-insensitive. Search before answering any "
        "question about their notes, plans or past; if nothing comes back, try other or fewer words.",
        {"query": str},
    )
    async def search_vault(args):
        return _ok(search_notes(vault, str(args.get("query", ""))))

    @tool(
        "read_note",
        "Read one note in full, by vault-relative path (e.g. 'Me/Devices.md') or by note "
        "name as in a [[wikilink]] (e.g. 'Devices'). Read a note before propose_edit so "
        "old_text matches it exactly.",
        {"path": str},
    )
    async def read_note_tool(args):
        try:
            return _ok(read_note(vault, args["path"]))
        except VaultError as e:
            return _err(str(e))

    @tool(
        "list_tags",
        "List the tags already used in the vault, most used first. Check this before "
        "tagging something and reuse an existing tag instead of inventing a near-duplicate.",
        {},
    )
    async def list_tags(args):
        return _ok(list_tags_text(vault))

    @tool(
        "list_tasks",
        "List open tasks ('- [ ]' lines) across the vault with where each lives. "
        "tag: optional filter without '#', e.g. 'dev'; '' for all open tasks.",
        {"tag": str},
    )
    async def list_tasks(args):
        return _ok(open_tasks(vault, str(args.get("tag", ""))))

    @tool(
        "capture",
        "Append one entry to today's daily note: anything the user wants noted down that isn't a "
        "lasting fact about them (use remember for those). task: true for something they have to "
        "do; it becomes a '- [ ]' checkbox tagged #todo. tags: space-separated, without '#', "
        "reusing existing tags (one or two topic tags). links: comma-separated names of "
        "EXISTING notes it relates to (find them with search_vault first); names that don't "
        "match a note are dropped. Use '' for none. due: 'YYYY-MM-DD' if the task has a "
        "date (\"remind me Friday\", \"by the 30th\"); work it out from today's date. The "
        "heartbeat reminds the user on that day. Use '' for none.",
        {"text": str, "task": bool, "tags": str, "links": str, "due": str},
    )
    async def capture(args):
        try:
            line, rel, dropped = capture_entry(vault, str(args.get("text", "")), bool(args.get("task")),
                                               str(args.get("tags", "")), str(args.get("links", "")),
                                               str(args.get("due", "") or ""))
        except VaultError as e:
            return _err(str(e))
        actions.append({"type": "captured", "path": rel, "line": line})
        if "- [ ]" in line:
            write_tasks_index(vault)
        reply = f"Saved to {rel}:\n{line}"
        if dropped:
            reply += f"\nLeft out these links because no such note exists: {', '.join(dropped)}"
        return _ok(reply)

    @tool(
        "propose_edit",
        "Propose changing an existing note. Nothing is written now: the user sees the change "
        "with Approve/Reject buttons, and it's applied only if they approve. old_text must "
        "appear exactly once in the note (copy it exactly, include enough context); "
        "new_text replaces it. Keep the change as small as possible.",
        {"path": str, "old_text": str, "new_text": str, "reason": str},
    )
    async def propose_edit(args):
        if sum(a["type"] == "proposal" for a in actions) >= MAX_PROPOSALS_PER_MESSAGE:
            return _err("Too many proposals in one message. Ask the user about the rest later.")
        try:
            rel = check_edit(vault, args["path"], args["old_text"], args["new_text"])
        except VaultError as e:
            return _err(str(e))
        actions.append({
            "type": "proposal",
            "path": rel,
            "old": args["old_text"],
            "new": args["new_text"],
            "reason": args.get("reason", ""),
        })
        return _ok(
            "Proposal recorded. It will be shown to the user with Approve/Reject buttons right "
            "after your reply; nothing has changed yet. In your reply, say briefly what "
            "you proposed; don't claim it's saved."
        )

    @tool(
        "escalate",
        "Hand the user's current message to a stronger model when you can't answer it well "
        "yourself: multi-step reasoning, non-trivial code or debugging, careful analysis, "
        "comparing options with real trade-offs, or long careful writing. Also when the user asks "
        "for a stronger model. Don't escalate small talk, simple questions, or saving facts. "
        f"Allowed models: {', '.join(escalate_to) or 'none'}. After calling this, don't answer "
        "the question yourself; end your turn with one short line. `reason` is a few words "
        "shown to the user, e.g. 'debugging a DB connection issue'.",
        {"model": str, "reason": str},
    )
    async def escalate(args):
        target = args.get("model", "").strip().lower()
        if target not in escalate_to:
            return _err(f"Can't escalate to '{target}'. Allowed: {', '.join(escalate_to) or 'none'}.")
        if any(a["type"] == "escalate" for a in actions):
            return _ok("Already escalated. End your turn.")
        actions.append({"type": "escalate", "model": target, "reason": " ".join(args.get("reason", "").split())[:120]})
        return _ok(f"OK. {target.title()} will answer the user's message right after this turn. "
                   "Don't answer it yourself; end your turn with one short line.")

    tools = [search_vault, read_note_tool, list_tags, list_tasks, capture, remember, propose_edit]
    tools += [escalate] if escalate_to else []
    return create_sdk_mcp_server("vault", tools=tools)
